def main():
    parser = argparse.ArgumentParser(
        description="LSTM Discriminator — Real vs Synthetic Distinguishability Test")
    parser.add_argument("--results-dir", default=str(DEFAULT_RESULTS_DIR))
    parser.add_argument("--output-dir", default=None,
                        help="Output directory (default: <results-dir>/lstm_discriminator)")
    parser.add_argument("--tickers", nargs="+", default=DEFAULT_TICKERS)
    args = parser.parse_args()

    results_dir = Path(args.results_dir)
    output_dir = args.output_dir or str(results_dir / "lstm_discriminator")
    os.makedirs(output_dir, exist_ok=True)

    print("=" * 70)
    print("LSTM DISCRIMINATOR — REAL vs SYNTHETIC")
    print("=" * 70)
    print(f"  Results dir: {results_dir}")
    print(f"  Output dir:  {output_dir}")
    print(f"  Tickers:     {args.tickers}")
    print(f"  Window:      {WINDOW_SIZE}")
    print(f"  Epochs:      {EPOCHS}")
    print(f"  Folds:       {N_FOLDS}")
    print("=" * 70)

    t_start = time.time()
    all_ticker_results: Dict[str, Dict] = {}

    for ticker in args.tickers:
        print(f"\n{'─' * 60}")
        print(f"  {ticker}")
        print(f"{'─' * 60}")

        real_path = results_dir / ticker / "real_data_reference.csv"
        synth_path = results_dir / ticker / "synthetic_data_causal_sde.csv"

        if not real_path.exists():
            print(f"  ⚠ {real_path} not found — skipping")
            continue
        if not synth_path.exists():
            print(f"  ⚠ {synth_path} not found — skipping")
            continue

        real_df = pd.read_csv(real_path)
        synth_df = pd.read_csv(synth_path)

        # Filter to available feature columns
        avail_cols = [c for c in FEATURE_COLS if c in real_df.columns and c in synth_df.columns]
        if not avail_cols:
            print(f"  ⚠ No matching feature columns — skipping")
            continue

        print(f"  Real:  {len(real_df)} rows, Synth: {len(synth_df)} rows")
        print(f"  Features: {avail_cols}")

        result = run_lstm_discriminator(real_df, synth_df, avail_cols)

        # Remove non-serialisable roc_data before saving
        roc_data = result.pop("roc_data", {})

        all_ticker_results[ticker] = result

        # ROC plot per ticker
        plot_roc_curves(roc_data, ticker, output_dir)

    elapsed = time.time() - t_start

    # ── Combined report ─────────────────────────────────────────
    report = {
        "experiment": "lstm_discriminator",
        "window_size": WINDOW_SIZE,
        "hidden_dim": HIDDEN_DIM,
        "epochs": EPOCHS,
        "n_folds": N_FOLDS,
        "elapsed_seconds": round(elapsed, 1),
        "per_ticker": all_ticker_results,
    }

    # Aggregate statistics
    ohlcv_accs = []
    ohlcv_aucs = []
    for tr in all_ticker_results.values():
        if tr.get("avg_accuracy"):
            ohlcv_accs.append(tr["avg_accuracy"])
        if tr.get("avg_auc_roc"):
            ohlcv_aucs.append(tr["avg_auc_roc"])

    if ohlcv_accs:
        report["aggregate"] = {
            "mean_accuracy_ohlcv": round(float(np.mean(ohlcv_accs)), 4),
            "std_accuracy_ohlcv": round(float(np.std(ohlcv_accs)), 4),
            "mean_auc_ohlcv": round(float(np.mean(ohlcv_aucs)), 4),
            "std_auc_ohlcv": round(float(np.std(ohlcv_aucs)), 4),
        }
        agg_acc = report["aggregate"]["mean_accuracy_ohlcv"]
        if agg_acc <= 0.55:
            report["aggregate"]["verdict"] = "EXCELLENT — practically indistinguishable"
        elif agg_acc <= 0.65:
            report["aggregate"]["verdict"] = "GOOD — minor distinguishable patterns"
        elif agg_acc <= 0.75:
            report["aggregate"]["verdict"] = "MODERATE — some systematic differences"
        else:
            report["aggregate"]["verdict"] = "POOR — clearly distinguishable"

    report_path = os.path.join(output_dir, "lstm_discriminator_report.json")
    with open(report_path, "w") as f:
        json.dump(report, f, indent=2)
    print(f"\n  Report: {report_path}")

    # Summary heatmap
    plot_summary_heatmap(all_ticker_results, output_dir)

    # ── Print summary ───────────────────────────────────────────
    print(f"\n{'=' * 70}")
    print("LSTM DISCRIMINATOR SUMMARY (OHLCV subset)")
    print(f"{'=' * 70}")
    print(f"  {'Ticker':<8} {'Accuracy':>10} {'AUC-ROC':>10} {'F1':>10}  Verdict")
    print(f"  {'─' * 62}")
    for ticker, tr in all_ticker_results.items():
        acc = tr.get("avg_accuracy", 0)
        auc = tr.get("avg_auc_roc", 0)
        f1 = tr.get("avg_f1", 0)
        v = tr.get("verdict", "—")
        print(f"  {ticker:<8} {acc:>10.4f} {auc:>10.4f} {f1:>10.4f}  {v}")

    if "aggregate" in report:
        agg = report["aggregate"]
        print(f"\n  Aggregate: acc={agg['mean_accuracy_ohlcv']:.4f} ± "
              f"{agg['std_accuracy_ohlcv']:.4f}  "
              f"AUC={agg['mean_auc_ohlcv']:.4f}  [{agg['verdict']}]")

    print(f"\n  Elapsed: {elapsed:.1f}s")
    print(f"  Output:  {output_dir}")
    print(f"{'=' * 70}")


if __name__ == "__main__":
    main()
