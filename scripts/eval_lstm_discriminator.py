def plot_roc_curves(roc_data: Dict[str, tuple], ticker: str, output_dir: str):
    """Plot multi-subset ROC curves for one ticker."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from sklearn.metrics import roc_curve

    if not roc_data:
        return

    palette = {
        "close":    {"color": "#1565C0", "ls": "-"},
        "volume":   {"color": "#E65100", "ls": "-"},
        "high_low": {"color": "#2E7D32", "ls": "--"},
        "ohlc":     {"color": "#C62828", "ls": "-."},
        "ohlcv":    {"color": "#6A1B9A", "ls": "-"},
    }
    display_names = {
        "close": "Close", "volume": "Volume", "high_low": "High+Low",
        "ohlc": "OHLC", "ohlcv": "OHLCV",
    }

    fig, ax = plt.subplots(figsize=(8, 8))

    for subset_name, (labels, probs, avg_auc) in roc_data.items():
        fpr, tpr, _ = roc_curve(labels, probs)
        style = palette.get(subset_name, {"color": "#546E7A", "ls": "-"})
        label = f"{display_names.get(subset_name, subset_name)} (AUC={avg_auc:.3f})"
        ax.plot(fpr, tpr, label=label, color=style["color"],
                linestyle=style["ls"], linewidth=2)

    ax.plot([0, 1], [0, 1], "k--", alpha=0.3, label="Random (AUC=0.500)")
    ax.set_xlabel("False Positive Rate", fontsize=12)
    ax.set_ylabel("True Positive Rate", fontsize=12)
    ax.set_title(f"LSTM Discriminator ROC — {ticker}\n"
                 f"(5-fold CV, window={WINDOW_SIZE})", fontsize=14, fontweight="bold")
    ax.legend(loc="lower right", fontsize=10)
    ax.set_xlim(-0.02, 1.02)
    ax.set_ylim(-0.02, 1.02)
    ax.set_aspect("equal")
    ax.grid(True, alpha=0.3)

    for ext in ("png", "pdf"):
        path = os.path.join(output_dir, f"roc_curves_{ticker}.{ext}")
        fig.savefig(path, dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved: roc_curves_{ticker}.png")


def plot_summary_heatmap(all_ticker_results: Dict[str, Dict], output_dir: str):
    """Heatmap of accuracy per ticker × feature subset."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    tickers = list(all_ticker_results.keys())
    subsets = ["close", "volume", "high_low", "ohlc", "ohlcv"]
    subset_labels = ["Close", "Volume", "High+Low", "OHLC", "OHLCV"]

    matrix = np.full((len(tickers), len(subsets)), np.nan)
    for i, ticker in enumerate(tickers):
        subs = all_ticker_results[ticker].get("subsets", {})
        for j, sn in enumerate(subsets):
            sr = subs.get(sn, {})
            if "avg_accuracy" in sr:
                matrix[i, j] = sr["avg_accuracy"]

    fig, ax = plt.subplots(figsize=(10, max(6, len(tickers) * 0.8 + 2)))

    # Custom diverging colormap: green (good/low acc) → red (bad/high acc)
    from matplotlib.colors import LinearSegmentedColormap
    cmap = LinearSegmentedColormap.from_list(
        "disc", ["#1B5E20", "#A5D6A7", "#FFEB3B", "#EF5350", "#B71C1C"]
    )
    im = ax.imshow(matrix, cmap=cmap, vmin=0.45, vmax=0.85, aspect="auto")

    ax.set_xticks(range(len(subsets)))
    ax.set_xticklabels(subset_labels, fontsize=11)
    ax.set_yticks(range(len(tickers)))
    ax.set_yticklabels(tickers, fontsize=11)

    for i in range(len(tickers)):
        for j in range(len(subsets)):
            val = matrix[i, j]
            if np.isnan(val):
                ax.text(j, i, "—", ha="center", va="center", fontsize=11, color="gray")
            else:
                color = "white" if val > 0.70 or val < 0.52 else "black"
                ax.text(j, i, f"{val:.3f}", ha="center", va="center",
                        fontsize=12, fontweight="bold", color=color)

    ax.set_title("LSTM Discriminator Accuracy\n(lower = more realistic)",
                 fontsize=14, fontweight="bold", pad=15)
    plt.colorbar(im, ax=ax, shrink=0.8, label="Accuracy (0.5 = indistinguishable)")

    plt.tight_layout()
    for ext in ("png", "pdf"):
        path = os.path.join(output_dir, f"summary_heatmap.{ext}")
        fig.savefig(path, dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved: summary_heatmap.png")


