"""
LSTM Discriminator — Real vs Synthetic Distinguishability Test.

Uses the same LSTM discriminator architecture from quality_report.py
to evaluate whether synthetic data generated by the Causal SDE pipeline
is distinguishable from real market data.

For each ticker, trains a 2-layer LSTM binary classifier with
group-aware shuffled 5-fold CV on multiple feature subsets
(close, volume, high_low, ohlc, ohlcv).

Output:
  results/final_run_gpt4o_mini/lstm_discriminator/
    lstm_discriminator_report.json
    roc_curves_<TICKER>.png / .pdf
    summary_heatmap.png / .pdf

Usage:
    python scripts/eval_lstm_discriminator.py
    python scripts/eval_lstm_discriminator.py --results-dir results/final_run_gpt4o_mini
    python scripts/eval_lstm_discriminator.py --tickers AAPL MSFT
"""

